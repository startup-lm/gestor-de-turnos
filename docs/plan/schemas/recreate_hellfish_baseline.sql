-- ==============================================================================
-- BASELINE PILOTO: Estructura Actual de Hellfish en Producción (Sin datos)
-- Para inicializar el proyecto de Supabase de TESTING idéntico al cliente piloto.
-- ==============================================================================

-- 1. Horarios
CREATE TABLE IF NOT EXISTS public.business_hours_global (
    id SMALLINT PRIMARY KEY DEFAULT 1,
    open_time TIME WITHOUT TIME ZONE NOT NULL,
    close_time TIME WITHOUT TIME ZONE NOT NULL,
    lunch_start TIME WITHOUT TIME ZONE,
    lunch_end TIME WITHOUT TIME ZONE,
    closed_days INTEGER[] NOT NULL DEFAULT '{}'::integer[]
);

-- 2. Configuración (versión original de Hellfish: solo slot_step_minutes)
CREATE TABLE IF NOT EXISTS public.business_settings (
    id SMALLINT PRIMARY KEY DEFAULT 1,
    slot_step_minutes INTEGER NOT NULL DEFAULT 30
);

-- 3. Barberos
CREATE TABLE IF NOT EXISTS public.barbers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    role TEXT NOT NULL,
    image TEXT,
    email TEXT,
    instagram TEXT,
    active BOOLEAN NOT NULL DEFAULT true,
    commission DOUBLE PRECISION,
    sale_commission DOUBLE PRECISION NOT NULL DEFAULT 0.2
);

-- 4. Servicios
CREATE TABLE IF NOT EXISTS public.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    description TEXT,
    price BIGINT,
    image TEXT,
    duration BIGINT NOT NULL
);

-- 5. Productos
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    description TEXT,
    price BIGINT,
    image TEXT
);

-- 6. Turnos
CREATE TABLE IF NOT EXISTS public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_id BIGINT,
    service_id BIGINT,
    client TEXT NOT NULL,
    phone TEXT,
    date DATE NOT NULL,
    start_time TIME WITHOUT TIME ZONE NOT NULL,
    end_time TIME WITHOUT TIME ZONE,
    paid BOOLEAN NOT NULL DEFAULT false,
    price BIGINT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    created_by TEXT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP WITH TIME ZONE,
    deleted_by TEXT
);

-- 7. Ventas
CREATE TABLE IF NOT EXISTS public.sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at DATE NOT NULL DEFAULT CURRENT_DATE,
    product_id BIGINT,
    barber_id BIGINT,
    price BIGINT,
    quantity BIGINT,
    total BIGINT,
    details TEXT
);

-- 8. Tabla existente en Hellfish
CREATE TABLE IF NOT EXISTS public.wa_sessions (
    id INTEGER PRIMARY KEY,
    phone TEXT NOT NULL,
    stage TEXT NOT NULL DEFAULT 'idle'::text,
    data JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    name TEXT
);
