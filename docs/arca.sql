-- ARCA settings + invoices tables (Supabase)
-- Ejecutar en el SQL editor de Supabase

create table if not exists arca_settings (
  id int primary key,
  environment text not null default 'mock',
  cuit text,
  point_of_sale int,
  cert_pem text,
  key_pem text,
  key_passphrase text,
  wsaa_url text,
  wsfe_url text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

insert into arca_settings (id, environment)
values (1, 'mock')
on conflict (id) do nothing;

create table if not exists arca_invoices (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  status text not null,
  total numeric not null,
  customer_name text,
  cae text,
  cae_due_date date,
  voucher_number int,
  voucher_type int,
  point_of_sale int,
  raw jsonb
);
