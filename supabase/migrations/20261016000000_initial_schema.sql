-- 1. Horarios globales del negocio
CREATE TABLE IF NOT EXISTS public.business_hours_global (
    id SMALLINT PRIMARY KEY DEFAULT 1,
    open_time TIME WITHOUT TIME ZONE NOT NULL,
    close_time TIME WITHOUT TIME ZONE NOT NULL,
    lunch_start TIME WITHOUT TIME ZONE,
    lunch_end TIME WITHOUT TIME ZONE,
    closed_days INTEGER[] NOT NULL DEFAULT '{}'::integer[]
);

-- 2. Configuración general, identidad y feature flags del negocio
CREATE TABLE IF NOT EXISTS public.business_settings (
    id SMALLINT PRIMARY KEY DEFAULT 1,
    slot_step_minutes INTEGER NOT NULL DEFAULT 30,
    phone TEXT,
    business_name TEXT DEFAULT 'Barbería Premium'::text,
    slogan TEXT,
    location_address TEXT,
    local_photo TEXT,
    business_logo TEXT,
    assignment_criteria TEXT DEFAULT 'random'::text,
    theme_colors JSONB,
    payment_methods JSONB DEFAULT '["Efectivo", "Mercado Pago"]'::jsonb,
    social_media JSONB DEFAULT '[{"url": "", "name": "instagram", "active": true}, {"url": "", "name": "facebook", "active": false}, {"url": "", "name": "tiktok", "active": false}]'::jsonb,
    our_story TEXT[] DEFAULT ARRAY[
        'Todo empezó en 2016, cuando armé una silla, un espejo y mi primera máquina en el garage de mi casa. Lo que arrancó como un hobby pronto se transformó en una pasión: brindar buenos cortes, charlas relajadas y un espacio donde todos se sintieran cómodos.'::text,
        'Con el tiempo, esa pequeña idea creció y dio lugar a este lugar, pensado para que cada visita sea una experiencia. Acá no se trata solo de cortarte el pelo o arreglarte la barba: se trata de dedicarte tiempo, escucharte y cuidar cada detalle.'::text,
        'Te esperamos para que disfrutes de un buen corte, un afeitado prolijo y un rato de desconexión de la rutina.'::text
    ],
    features JSONB NOT NULL DEFAULT '{}'::jsonb
);

-- 3. Barberos del local
CREATE TABLE IF NOT EXISTS public.barbers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    role TEXT NOT NULL DEFAULT 'barber'::text,
    image TEXT,
    email TEXT NOT NULL,
    instagram TEXT,
    active BOOLEAN NOT NULL DEFAULT true,
    commission DOUBLE PRECISION,
    sale_commission DOUBLE PRECISION NOT NULL DEFAULT 0.2
);

-- 4. Servicios disponibles
CREATE TABLE IF NOT EXISTS public.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    description TEXT,
    price BIGINT,
    image TEXT,
    duration BIGINT NOT NULL DEFAULT 30
);

-- 5. Productos para venta en mostrador
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    description TEXT,
    price BIGINT,
    image TEXT,
    stock INTEGER DEFAULT 0
);

-- 6. Libreta de clientes recurrentes (reserva rápida / autocompletado)
CREATE TABLE IF NOT EXISTS public.clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    last_visit_date DATE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 7. Facturación fiscal ARCA / AFIP
CREATE TABLE IF NOT EXISTS public.arca_settings (
    id INTEGER PRIMARY KEY DEFAULT 1,
    environment TEXT NOT NULL DEFAULT 'mock'::text,
    cuit TEXT,
    point_of_sale INTEGER,
    cert_pem TEXT,
    key_pem TEXT,
    key_passphrase TEXT,
    wsaa_url TEXT,
    wsfe_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.arca_invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    status TEXT NOT NULL,
    total NUMERIC NOT NULL,
    customer_name TEXT,
    cae TEXT,
    cae_due_date DATE,
    voucher_number INTEGER,
    voucher_type INTEGER,
    point_of_sale INTEGER,
    raw JSONB,
    source_type TEXT,
    source_id BIGINT,
    doc_type INTEGER,
    doc_number TEXT,
    invoice_type INTEGER DEFAULT 11
);

-- 8. Turnos y reservas
CREATE TABLE IF NOT EXISTS public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_id BIGINT REFERENCES public.barbers(id) ON DELETE SET NULL,
    service_id BIGINT REFERENCES public.services(id) ON DELETE SET NULL DEFAULT 1,
    client_id BIGINT REFERENCES public.clients(id) ON DELETE SET NULL,
    arca_invoice_id BIGINT REFERENCES public.arca_invoices(id) ON DELETE SET NULL,
    client TEXT NOT NULL,
    phone TEXT,
    date DATE NOT NULL,
    start_time TIME WITHOUT TIME ZONE NOT NULL,
    end_time TIME WITHOUT TIME ZONE,
    paid BOOLEAN NOT NULL DEFAULT false,
    price BIGINT,
    payment_method TEXT,
    type TEXT DEFAULT 'appointment'::text,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    created_by TEXT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    deleted_at TIMESTAMP WITH TIME ZONE,
    deleted_by TEXT
);

-- 9. Ventas registradas
CREATE TABLE IF NOT EXISTS public.sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at DATE NOT NULL DEFAULT CURRENT_DATE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    barber_id BIGINT REFERENCES public.barbers(id) ON DELETE SET NULL,
    arca_invoice_id BIGINT REFERENCES public.arca_invoices(id) ON DELETE SET NULL,
    price BIGINT,
    quantity BIGINT,
    total BIGINT,
    details TEXT
);

-- 10. Índices para performance
CREATE INDEX IF NOT EXISTS idx_appointments_date_barber ON public.appointments(date, barber_id);
CREATE INDEX IF NOT EXISTS idx_appointments_client_id ON public.appointments(client_id);
CREATE INDEX IF NOT EXISTS idx_sales_created_at ON public.sales(created_at);
CREATE INDEX IF NOT EXISTS idx_clients_phone ON public.clients(phone);
