-- 1. Crear tablas nuevas que faltan en los clientes
-- ------------------------------------------------------------------------------

-- Tabla de clientes para autocompletado y fidelización
CREATE TABLE IF NOT EXISTS public.clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    last_visit_date DATE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_clients_phone ON public.clients(phone);

-- Tablas de facturación ARCA (nacen inactivas mientras flag arca = false)
CREATE TABLE IF NOT EXISTS public.arca_settings (
    id INTEGER PRIMARY KEY DEFAULT 1,
    environment TEXT NOT NULL DEFAULT 'mock'::text,
    cuit TEXT,
    point_of_sale INTEGER,
    cert_pem TEXT,
    key_pem TEXT,
    key_passphrase TEXT,
    wsaa_url TEXT,
    wsfe_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.arca_invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    status TEXT NOT NULL,
    total NUMERIC NOT NULL,
    customer_name TEXT,
    cae TEXT,
    cae_due_date DATE,
    voucher_number INTEGER,
    voucher_type INTEGER,
    point_of_sale INTEGER,
    raw JSONB,
    source_type TEXT,
    source_id BIGINT,
    doc_type INTEGER,
    doc_number TEXT,
    invoice_type INTEGER DEFAULT 11
);

-- 2. Expandir business_settings con soporte dinámico y feature flags
-- ------------------------------------------------------------------------------
ALTER TABLE public.business_settings 
    ADD COLUMN IF NOT EXISTS phone TEXT,
    ADD COLUMN IF NOT EXISTS business_name TEXT DEFAULT 'Barbería Premium'::text,
    ADD COLUMN IF NOT EXISTS slogan TEXT,
    ADD COLUMN IF NOT EXISTS location_address TEXT,
    ADD COLUMN IF NOT EXISTS local_photo TEXT,
    ADD COLUMN IF NOT EXISTS business_logo TEXT,
    ADD COLUMN IF NOT EXISTS assignment_criteria TEXT DEFAULT 'random'::text,
    ADD COLUMN IF NOT EXISTS theme_colors JSONB,
    ADD COLUMN IF NOT EXISTS payment_methods JSONB DEFAULT '["Efectivo", "Mercado Pago"]'::jsonb,
    ADD COLUMN IF NOT EXISTS social_media JSONB DEFAULT '[]'::jsonb,
    ADD COLUMN IF NOT EXISTS our_story TEXT[],
    ADD COLUMN IF NOT EXISTS features JSONB NOT NULL DEFAULT '{}'::jsonb;

-- 3. Expandir appointments con trazabilidad, métodos de pago y FKs
-- ------------------------------------------------------------------------------
ALTER TABLE public.appointments 
    ADD COLUMN IF NOT EXISTS client_id BIGINT REFERENCES public.clients(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS payment_method TEXT,
    ADD COLUMN IF NOT EXISTS type TEXT DEFAULT 'appointment'::text,
    ADD COLUMN IF NOT EXISTS arca_invoice_id BIGINT REFERENCES public.arca_invoices(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_appointments_client_id ON public.appointments(client_id);

-- 4. Expandir products con stock
-- ------------------------------------------------------------------------------
ALTER TABLE public.products 
    ADD COLUMN IF NOT EXISTS stock INTEGER DEFAULT 0;

-- 5. Expandir sales con relación a facturas ARCA
-- ------------------------------------------------------------------------------
ALTER TABLE public.sales 
    ADD COLUMN IF NOT EXISTS arca_invoice_id BIGINT REFERENCES public.arca_invoices(id) ON DELETE SET NULL;

-- 6. Homologar defaults y tipos sin romper datos
-- ------------------------------------------------------------------------------
ALTER TABLE public.appointments ALTER COLUMN service_id SET DEFAULT 1;
ALTER TABLE public.barbers ALTER COLUMN role SET DEFAULT 'barber'::text;
ALTER TABLE public.services ALTER COLUMN duration SET DEFAULT 30;

