-- Versión: 20261028000000_cash_management_and_payouts.sql
-- Descripción:
--   1. Agrega columna cash_closing_frequency en business_settings ('daily' | 'weekly' | 'manual').
--   2. Crea tabla cash_shifts para arqueos y sesiones de caja.
--   3. Crea tabla cash_movements para registrar egresos, gastos e ingresos manuales.
--   4. Crea tabla commission_payouts para historial oficial de liquidaciones a profesionales.
-- ==============================================================================

-- 1. Frecuencia de Cierre de Caja en business_settings
ALTER TABLE public.business_settings 
ADD COLUMN IF NOT EXISTS cash_closing_frequency TEXT NOT NULL DEFAULT 'daily';

-- 2. Sesiones de Caja (Turnos / Períodos de Caja)
CREATE TABLE IF NOT EXISTS public.cash_shifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opened_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    closed_at TIMESTAMP WITH TIME ZONE,
    opened_by TEXT NOT NULL,
    closed_by TEXT,
    initial_cash NUMERIC NOT NULL DEFAULT 0,
    expected_cash NUMERIC,
    actual_cash NUMERIC,
    cash_difference NUMERIC,
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. Movimientos de Caja (Egresos, Ingressos manuales, Adelantos, Retiros)
CREATE TABLE IF NOT EXISTS public.cash_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT REFERENCES public.cash_shifts(id) ON DELETE SET NULL,
    barber_id BIGINT REFERENCES public.barbers(id) ON DELETE SET NULL,
    type TEXT NOT NULL CHECK (type IN ('income', 'expense', 'advance', 'withdrawal', 'commission_payout')),
    category TEXT NOT NULL, -- 'insumos', 'servicios', 'limpieza', 'adelanto', 'retiro_dueno', 'comision', 'otro'
    amount NUMERIC NOT NULL,
    payment_method TEXT NOT NULL DEFAULT 'Efectivo',
    description TEXT NOT NULL,
    reference_code TEXT, -- Opcional: nº de transferencia o comprobante externo
    created_by TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Historial de Pagos de Comisiones / Liquidaciones
CREATE TABLE IF NOT EXISTS public.commission_payouts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_id BIGINT NOT NULL REFERENCES public.barbers(id) ON DELETE CASCADE,
    shift_id BIGINT REFERENCES public.cash_shifts(id) ON DELETE SET NULL,
    movement_id BIGINT REFERENCES public.cash_movements(id) ON DELETE SET NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    cuts_count INTEGER NOT NULL DEFAULT 0,
    cuts_commission_amount NUMERIC NOT NULL DEFAULT 0,
    sales_count INTEGER NOT NULL DEFAULT 0,
    sales_commission_amount NUMERIC NOT NULL DEFAULT 0,
    advances_deducted NUMERIC NOT NULL DEFAULT 0,
    total_paid NUMERIC NOT NULL,
    payment_method TEXT NOT NULL DEFAULT 'Efectivo',
    payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    reference_code TEXT,
    receipt_notes TEXT,
    paid_by TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. Índices de consulta rápida
CREATE INDEX IF NOT EXISTS idx_cash_shifts_status ON public.cash_shifts(status);
CREATE INDEX IF NOT EXISTS idx_cash_movements_shift_id ON public.cash_movements(shift_id);
CREATE INDEX IF NOT EXISTS idx_cash_movements_barber_id ON public.cash_movements(barber_id);
CREATE INDEX IF NOT EXISTS idx_cash_movements_created_at ON public.cash_movements(created_at);
CREATE INDEX IF NOT EXISTS idx_cash_movements_type ON public.cash_movements(type);
CREATE INDEX IF NOT EXISTS idx_commission_payouts_barber_period ON public.commission_payouts(barber_id, period_start, period_end);
CREATE INDEX IF NOT EXISTS idx_commission_payouts_payment_date ON public.commission_payouts(payment_date);

-- 6. Seguridad: Habilitar RLS (Row Level Security)
-- Las tablas quedan protegidas contra accesos directos desde el cliente anónimo (anon key).
-- La API de Next.js accede mediante supabaseAdmin (service_role) con verificación de rol admin.
ALTER TABLE public.cash_shifts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cash_movements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.commission_payouts ENABLE ROW LEVEL SECURITY;

